#!/bin/bash
# ./scripts/generate_ca_header.sh
#
# Converts PEM CA certificates from the server repo into a C header
# (wolfssl/include/ca_certs.h) that the firmware embeds for DTLS
# server certificate verification.
#
# Reads directly from:
#   qeaas-server/coap2http-proxy/certs/ecc/ca-ecc-cert.pem     → ECDSA P-256 CA
#   qeaas-server/coap2http-proxy/certs/mldsa44/mldsa44_root_cert.pem → ML-DSA-44 CA
#
# Called automatically by build.sh before each build.

set -e

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVER_CERTS="$PROJECT_ROOT/qeaas-server/coap2http-proxy/certs"
OUTPUT="$PROJECT_ROOT/wolfssl/include/ca_certs.h"

ECC_PEM="$SERVER_CERTS/ecc/ca-ecc-cert.pem"
MLDSA44_PEM="$SERVER_CERTS/mldsa44/mldsa44_root_cert.pem"

# Convert a PEM file to a C string literal (one quoted line per PEM line)
pem_to_c_string() {
    local file="$1"
    while IFS= read -r line; do
        printf '    "%s\\n"\n' "$line"
    done < "$file"
}

has_ecc=false
has_mldsa44=false
[ -f "$ECC_PEM" ]     && has_ecc=true
[ -f "$MLDSA44_PEM" ] && has_mldsa44=true

if ! $has_ecc && ! $has_mldsa44; then
    echo "generate_ca_header: no CA certs found in $SERVER_CERTS — generating stub"
    echo "  (clone qeaas-server into project root: git clone https://github.com/qursa-uc3m/qeaas-server.git)"
fi

cat > "$OUTPUT" << 'HEADER'
/* Auto-generated by scripts/generate_ca_header.sh — do not edit manually.
 * Reads CA certs from qeaas-server/coap2http-proxy/certs/.
 *   ecc/ca-ecc-cert.pem              → ECDSA P-256 CA
 *   mldsa44/mldsa44_root_cert.pem    → ML-DSA-44 CA
 */
#ifndef CA_CERTS_H
#define CA_CERTS_H

HEADER

if $has_mldsa44; then
    echo "/* ML-DSA-44 Root CA */" >> "$OUTPUT"
    echo "static const char ca_cert_mldsa44_pem[] =" >> "$OUTPUT"
    pem_to_c_string "$MLDSA44_PEM" >> "$OUTPUT"
    echo ";" >> "$OUTPUT"
    echo "" >> "$OUTPUT"
    echo "generate_ca_header: embedded ML-DSA-44 CA ($(wc -c < "$MLDSA44_PEM") bytes)"
else
    echo "static const char ca_cert_mldsa44_pem[] = \"\";" >> "$OUTPUT"
    echo "" >> "$OUTPUT"
fi

if $has_ecc; then
    echo "/* ECDSA P-256 CA */" >> "$OUTPUT"
    echo "static const char ca_cert_ecc_pem[] =" >> "$OUTPUT"
    pem_to_c_string "$ECC_PEM" >> "$OUTPUT"
    echo ";" >> "$OUTPUT"
    echo "" >> "$OUTPUT"
    echo "generate_ca_header: embedded ECC CA ($(wc -c < "$ECC_PEM") bytes)"
else
    echo "static const char ca_cert_ecc_pem[] = \"\";" >> "$OUTPUT"
    echo "" >> "$OUTPUT"
fi

echo "#endif /* CA_CERTS_H */" >> "$OUTPUT"
echo "generate_ca_header: wrote $OUTPUT"
